import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const publicDir = path.join(__dirname, '../public')
const routesPath = path.join(__dirname, '../src/locationRoutes.jsx')
const siteUrl = (process.env.SITE_URL || process.env.VITE_SITE_URL || 'https://7statespestcontrol.com.au').replace(
  /\/$/,
  '',
)
const outPath = path.join(publicDir, 'location-sitemap.xml')
const indexFiles = ['sitemap_index.xml', 'sitemap.xml']

function readLocationPaths() {
  const src = fs.readFileSync(routesPath, 'utf8')
  const paths = [...src.matchAll(/path:\s*['"](location(?:\/[^'"]+)?)['"]/g)].map((m) => m[1])
  return [...new Set(paths)]
}

function readExistingLastmods() {
  const map = new Map()
  if (!fs.existsSync(outPath)) return map
  const xml = fs.readFileSync(outPath, 'utf8')
  for (const match of xml.matchAll(/<url>\s*<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) {
    map.set(match[1], match[2])
  }
  return map
}

function toLoc(routePath) {
  return `${siteUrl}/${routePath.replace(/\/$/, '')}/`
}

function buildLocationSitemap(paths, lastmods) {
  const fallbackLastmod = new Date().toISOString().replace(/\.\d{3}Z$/, '+00:00')
  const urls = paths
    .map((p) => {
      const loc = toLoc(p)
      const lastmod = lastmods.get(loc) || fallbackLastmod
      return `\t<url>\n\t\t<loc>${loc}</loc>\n\t\t<lastmod>${lastmod}</lastmod>\n\t</url>`
    })
    .join('\n')

  return `<?xml version="1.0" encoding="UTF-8"?><?xml-stylesheet type="text/xsl" href="/main-sitemap.xsl"?>
<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
<!-- XML Sitemap generated by Yoast SEO -->
`
}

function ensureIndexIncludesLocation(file) {
  const filePath = path.join(publicDir, file)
  if (!fs.existsSync(filePath)) return false

  let xml = fs.readFileSync(filePath, 'utf8')
  const locationLoc = `${siteUrl}/location-sitemap.xml`
  if (xml.includes(locationLoc)) return false

  const lastmod = new Date().toISOString().replace(/\.\d{3}Z$/, '+00:00')
  const entry = `\t<sitemap>
\t\t<loc>${locationLoc}</loc>
\t\t<lastmod>${lastmod}</lastmod>
\t</sitemap>
`
  // Insert after elementskit (Yoast order) when present; otherwise before </sitemapindex>
  if (xml.includes('elementskit_template-sitemap.xml')) {
    xml = xml.replace(
      /(<\/sitemap>\s*)(<sitemap>\s*<loc>[^<]*category-sitemap\.xml<\/loc>)/,
      `$1${entry}$2`,
    )
    if (!xml.includes(locationLoc)) {
      xml = xml.replace(
        /(<\/sitemap>\s*)(<\/sitemapindex>)/,
        `$1${entry}$2`,
      )
    }
  } else {
    xml = xml.replace(/(<\/sitemap>\s*)(<\/sitemapindex>)/, `$1${entry}$2`)
  }

  fs.writeFileSync(filePath, xml, 'utf8')
  return true
}

const paths = readLocationPaths()
if (!paths.length) {
  console.error('No location routes found in locationRoutes.jsx')
  process.exit(1)
}

const lastmods = readExistingLastmods()
const xml = buildLocationSitemap(paths, lastmods)
fs.mkdirSync(publicDir, { recursive: true })
fs.writeFileSync(outPath, xml, 'utf8')
console.log(`Wrote location-sitemap.xml (${paths.length} URLs)`)

for (const file of indexFiles) {
  if (ensureIndexIncludesLocation(file)) {
    console.log(`Added location-sitemap.xml entry to ${file}`)
  }
}
