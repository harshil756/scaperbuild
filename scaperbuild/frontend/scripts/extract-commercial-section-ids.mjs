/**
 * Extract Elementor widget IDs for commercial page CMS sections.
 * Run: node scripts/extract-commercial-section-ids.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '../..')

const PAGES = [
  { slug: 'office-pest-control', file: 'frontend/src/pages/commercial/OfficePestControlPage.jsx' },
  { slug: 'restaurant-cafe-pest-control', file: 'frontend/src/pages/commercial/RestaurantCafePestControlPage.jsx' },
  { slug: 'school-and-hospitality-facility-pest-control', file: 'frontend/src/pages/commercial/SchoolAndHospitalityFacilityPestControlPage.jsx' },
  { slug: 'warehouse-and-factory-pest-control-services-melbourne', file: 'frontend/src/pages/commercial/WarehouseAndFactoryPestControlServicesMelbournePage.jsx' },
]

function widgetIdBefore(jsx, needle, from = 0) {
  const idx = jsx.indexOf(needle, from)
  if (idx === -1) return null
  const before = jsx.slice(Math.max(0, idx - 800), idx)
  const ids = [...before.matchAll(/data-id="([a-f0-9]+)"/g)]
  return ids.at(-1)?.[1] ?? null
}

function widgetIdAfter(jsx, needle) {
  const idx = jsx.indexOf(needle)
  if (idx === -1) return null
  const chunk = jsx.slice(idx, idx + 600)
  const m = chunk.match(/data-id="([a-f0-9]+)"/)
  return m?.[1] ?? null
}

function extract(jsx) {
  const whyIdx = jsx.indexOf('>Why Choose<')
  const touchIdx = jsx.indexOf('Get in Touch')
  const svcIdx = jsx.indexOf('>Our Services')

  return {
    about: {
      counter: jsx.match(/data-id="([^"]+)"[^>]*data-widget_type="counter\.default"/)?.[1] ?? null,
      title: widgetIdBefore(jsx, 'Pest control service for your offices') ?? widgetIdBefore(jsx, 'pest control service'),
      subtitle: widgetIdAfter(jsx, 'Pest control service for your offices') ?? widgetIdAfter(jsx, 'pest control service'),
      intro: widgetIdBefore(jsx, 'When you choose Assured') ?? widgetIdBefore(jsx, 'When you choose'),
    },
    whyChoose: {
      eyebrow: whyIdx > 0 ? widgetIdBefore(jsx, '>Why Choose<', whyIdx - 1) : null,
      title: whyIdx > 0 ? widgetIdAfter(jsx, '>Why Choose<') : null,
      intro: whyIdx > 0 ? widgetIdBefore(jsx, 'We believe in offering the best solutions') : null,
    },
    contact: {
      eyebrow: touchIdx > 0 ? widgetIdBefore(jsx, 'Get in Touch') : null,
      title: touchIdx > 0 ? widgetIdAfter(jsx, 'Get in Touch') : null,
      body: widgetIdAfter(jsx, 'Contact 7 States Pest Control'),
      button: jsx.match(/Our Locations[\s\S]{0,400}?data-id="([a-f0-9]+)"[\s\S]{0,120}?elementor-button/)?.[1] ?? null,
    },
    services: {
      eyebrow: svcIdx > 0 ? widgetIdBefore(jsx, '>Our Services') : null,
      title: svcIdx > 0 ? widgetIdAfter(jsx, '>Our Services') : null,
      intro: widgetIdBefore(jsx, 'one-stop destination') ?? widgetIdBefore(jsx, '7 States Pest Control is your one-stop'),
    },
  }
}

const out = {}
for (const page of PAGES) {
  const jsx = fs.readFileSync(path.join(root, page.file), 'utf8')
  out[page.slug] = extract(jsx)
  console.log(page.slug, JSON.stringify(out[page.slug], null, 2))
}

fs.writeFileSync(
  path.join(__dirname, '../src/config/commercialPageCmsSections.js'),
  `// Auto-generated by scripts/extract-commercial-section-ids.mjs
export const COMMERCIAL_PAGE_CMS_SECTIONS = ${JSON.stringify(out, null, 2)}
`,
  'utf8',
)
console.log('\nWrote frontend/src/config/commercialPageCmsSections.js')
