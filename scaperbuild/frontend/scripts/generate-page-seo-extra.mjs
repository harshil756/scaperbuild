import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { extractSeoFromHtml } from './extract-seo-from-html.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '../..')
const exportRoot = path.join(root, 'export/7statespestcontrol.com.au')
const outPath = path.join(__dirname, '../src/config/pageSeoExtra.js')

function findHtmlFile(dir) {
  const direct = path.join(dir, `${path.basename(dir)}.html`)
  if (fs.existsSync(direct)) return direct
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.html'))
  if (files.length === 1) return path.join(dir, files[0])
  return null
}

const seoBySlug = {}

for (const entry of fs.readdirSync(exportRoot, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const htmlPath = findHtmlFile(path.join(exportRoot, entry.name))
  if (!htmlPath) continue
  const html = fs.readFileSync(htmlPath, 'utf8')
  const seo = extractSeoFromHtml(html)
  if (seo.canonical || seo.jsonLd || Object.keys(seo.og).length) {
    seoBySlug[entry.name] = seo
  }
}

// Thank-you page may not be in export yet; fetch from live if missing
if (!seoBySlug['thank-you']) {
  try {
    const res = await fetch('https://7statespestcontrol.com.au/thank-you/')
    if (res.ok) {
      const html = await res.text()
      seoBySlug['thank-you'] = extractSeoFromHtml(html)
    }
  } catch {
    // ignore network errors during build
  }
}

const lines = [
  '// Auto-generated by scripts/generate-page-seo-extra.mjs',
  '// SEO data extracted from exported WordPress HTML (Yoast)',
  'export const PAGE_SEO_EXTRA = ' + JSON.stringify(seoBySlug, null, 2),
  '',
]

fs.writeFileSync(outPath, lines.join('\n'), 'utf8')
console.log(`Wrote ${outPath} (${Object.keys(seoBySlug).length} pages)`)
